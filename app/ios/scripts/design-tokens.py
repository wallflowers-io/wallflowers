#!/usr/bin/env python3
"""design-tokens — carry the app's design constants into the UI diagram.

Swift is authoritative. `ui/App/Design/DesignTokens.swift` is the single
source; this script parses it and rewrites the CSS block between the @tokens
markers in the one-pager, so the diagram measures what the app measures instead
of what somebody transcribed.

    design-tokens.py PAGE            rewrite PAGE's token block
    design-tokens.py --check PAGE    exit 1 if PAGE's block is stale

WHY A GENERATOR AND NOT A TEST. A test tells you the two copies disagree; this
removes the second copy. The diagram's numbers are derived here, every time, so
"the CSS drifted from the Swift" stops being a state the tree can be in.

THE UNIT PROBLEM. Swift measures in points on a 393pt-wide screen. The diagram
draws a phone frame of arbitrary CSS width, so nothing can be emitted in px. Two
relative units carry the tokens across:

  em   against the screen's own font-size, for anything positioned in the frame
       (the frame is `designWidth` points wide, so 1pt = 28/designWidth em).
  cqw  against a CARD's width, for anything inside one. A card is
       designWidth - 2*Life.gutter points wide, so 1pt = 100/that cqw.

Both fall out of the tokens; neither is a constant anyone maintains.
"""

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SWIFT = ROOT / "ui/App/Design/DesignTokens.swift"

BEGIN = "  /* @tokens — generated by pacific/scripts/design-tokens.py. Do not edit. */"
END = "  /* @end-tokens */"

# The frame's own em, in px. `.scr` sets this; it is the diagram's scale anchor.
SCR_EM = 7.0


def parse_swift(text):
    """`static let name: CGFloat = 12.5` -> {"Enum.name": 12.5}, plus the one Color."""
    out, enum = {}, None
    for line in text.splitlines():
        m = re.match(r"\s*enum (\w+) \{", line)
        if m and m.group(1) != "DesignTokens":
            enum = m.group(1)
            continue
        # a trailing `// …` is allowed: several tokens carry the arithmetic they
        # came from (`0.24  // 0.6 / 2.5`), which is worth keeping beside them
        m = re.match(r"\s*static let (\w+):?\s*(?:CGFloat|Double)?\s*=\s*([0-9.]+)\s*(?://.*)?$", line)
        if m and enum:
            out[f"{enum}.{m.group(1)}"] = float(m.group(2))
            continue
        m = re.match(r"\s*static let (\w+) = Color\(red: ([\d.]+), green: ([\d.]+), blue: ([\d.]+)\)", line)
        if m and enum:
            out[f"{enum}.{m.group(1)}"] = tuple(round(float(m.group(i)) * 255) for i in (2, 3, 4))
            continue
        # A DYNAMIC pair — `Theme.dyn(light: 0xAABBCC, dark: 0xDDEEFF)`. The diagram is
        # drawn on the dark ground, so it takes the DARK half; the light half is the
        # inverted mode's and has no place in a diagram of the app at rest.
        #
        # This arm exists because tokens acquire a light twin over time and the parser
        # used to fail with a bare KeyError when one did — which took `just build`
        # down with it, since `build` depends on `tokens-check`. A token the parser cannot
        # read should never be able to stop the app compiling.
        m = re.match(r"\s*static let (\w+) = Theme\.dyn\(light: 0x([0-9A-Fa-f]{6}), dark: 0x([0-9A-Fa-f]{6})\)", line)
        if m and enum:
            hexval = m.group(3)
            out[f"{enum}.{m.group(1)}"] = tuple(int(hexval[i:i + 2], 16) for i in (0, 2, 4))
    return out


def render(t):
    W = t["Screen.designWidth"]
    em = lambda pt: f"{pt * 28.0 / W:.4g}em"          # frame is 28em wide (196px / 7)
    card_w = W - 2 * t["Life.gutter"]
    cqw = lambda pt: f"{pt * 100.0 / card_w:.4g}cqw"  # against a card's own width
    r, g, b = t["Rail.opal"]

    L = [BEGIN,
         f"  /* {SWIFT.name}: 1pt = {28.0 / W:.5f}em of the frame, and",
         f"     1pt = {100.0 / card_w:.5f}cqw inside a card ({W:g} - 2*{t['Life.gutter']:g}"
         f" = {card_w:g}pt wide). */",
         "  :root{"]

    def row(name, val, comment):
        L.append(f"    --{name}:{val};".ljust(38) + f"/* {comment} */")

    row("t-life-gutter", em(t["Life.gutter"]), f"Life.gutter {t['Life.gutter']:g}pt \u2014 ONE inset for the whole tab")
    row("t-feed-gap", em(t["Feed.stackSpacing"]), f"Feed.stackSpacing {t['Feed.stackSpacing']:g}pt")
    # the Profile — heights are RATIOS of a card's width, so they stay unitless
    # and the diagram multiplies; the bar and radius are lengths.
    row("t-p-head-space", f"{t['Profile.headlineSpace']:g}", "Profile.headlineSpace (x card width)")
    row("t-p-head-person", f"{t['Profile.headlinePerson']:g}", "Profile.headlinePerson (x card width)")
    row("t-p-info", f"{t['Profile.info']:g}", "Profile.info (x card width) \u2014 the bio band shares it")
    row("t-p-bar", em(t["Profile.bar"]), f"Profile.bar {t['Profile.bar']:g}pt")
    row("t-p-gap", em(t["Profile.cardSpacing"]), f"Profile.cardSpacing {t['Profile.cardSpacing']:g}pt")
    row("t-p-vpad", em(t["Profile.verticalPad"]), f"Profile.verticalPad {t['Profile.verticalPad']:g}pt")
    row("t-p-bandpad", em(t["Profile.bandPad"]), f"Profile.bandPad {t['Profile.bandPad']:g}pt")
    # the selector rail: glyph alone in an equal slot, a rule under the active one
    row("t-p-jglyph", em(t["Profile.jewelGlyph"]), f"Profile.jewelGlyph {t['Profile.jewelGlyph']:g}pt")
    row("t-p-radius", em(t["Profile.radius"]), f"Profile.radius {t['Profile.radius']:g}pt (Sig.modalRadius)")
    # the Room: tabs, and the one nesting step
    row("t-r-tabh", em(t["Room.tabPadH"]), f"Room.tabPadH {t['Room.tabPadH']:g}pt")
    row("t-r-tabv", em(t["Room.tabPadV"]), f"Room.tabPadV {t['Room.tabPadV']:g}pt")
    row("t-r-indent", em(t["Room.indentUnit"]), f"Room.indentUnit {t['Room.indentUnit']:g}pt \u2014 one nesting step")
    row("t-r-posth", em(t["Room.postPadH"]), f"Room.postPadH {t['Room.postPadH']:g}pt")
    row("t-r-postv", em(t["Room.postPadV"]), f"Room.postPadV {t['Room.postPadV']:g}pt")
    row("t-r-railgap", em(t["Room.railGap"]), f"Room.railGap {t['Room.railGap']:g}pt")
    # the Chat bubble
    row("t-b-radius", em(t["Chat.bubbleRadius"]), f"Chat.bubbleRadius {t['Chat.bubbleRadius']:g}pt")
    row("t-b-tail", em(t["Chat.bubbleTail"]), f"Chat.bubbleTail {t['Chat.bubbleTail']:g}pt \u2014 the sender's corner")
    row("t-b-padh", em(t["Chat.bubblePadH"]), f"Chat.bubblePadH {t['Chat.bubblePadH']:g}pt")
    row("t-b-padv", em(t["Chat.bubblePadV"]), f"Chat.bubblePadV {t['Chat.bubblePadV']:g}pt")
    row("t-b-inset", em(t["Chat.bubbleInset"]), f"Chat.bubbleInset {t['Chat.bubbleInset']:g}pt \u2014 the far margin")
    row("t-b-gap", em(t["Chat.gapDistinct"]), f"Chat.gapDistinct {t['Chat.gapDistinct']:g}pt")
    row("t-b-gapg", em(t["Chat.gapGrouped"]), f"Chat.gapGrouped {t['Chat.gapGrouped']:g}pt")
    # the disc row — the gaps are what animate
    row("t-d-size", em(t["Discs.size"]), f"Discs.size {t['Discs.size']:g}pt")
    row("t-d-rest", em(t["Discs.restGap"]), f"Discs.restGap {t['Discs.restGap']:g}pt")
    row("t-d-edge", em(t["Discs.rowEdge"]), f"Discs.rowEdge {t['Discs.rowEdge']:g}pt")
    row("t-d-compose", em(t["Discs.composeGap"]), f"Discs.composeGap {t['Discs.composeGap']:g}pt \u2014 the closing gap")
    # the detail hero, in frame-em: what a tapped card expands INTO
    row("t-event-hero", em(t["Event.heroHeight"]), f"Event.heroHeight {t['Event.heroHeight']:g}pt")
    row("t-feed-top", em(t["Rail.jewel"] + t["Feed.topGap"]),
        f"Rail.jewel + Feed.topGap = {t['Rail.jewel'] + t['Feed.topGap']:g}pt")
    row("t-rail-jewel", em(t["Rail.jewel"]), f"Rail.jewel {t['Rail.jewel']:g}pt")
    row("t-rail-inset", em(t["Rail.inset"]), f"Rail.inset {t['Rail.inset']:g}pt")
    row("t-rail-gap", em(t["Rail.gap"]), f"Rail.gap {t['Rail.gap']:g}pt")
    row("t-rail-top", em(t["Rail.topPad"]), f"Rail.topPad {t['Rail.topPad']:g}pt")
    row("t-rail-glyph", em(t["Rail.jewel"] * t["Rail.glyphRatio"]),
        f"jewel * glyphRatio {t['Rail.glyphRatio']:g}")
    row("t-rail-stroke", em(t["Rail.stroke"]), f"Rail.stroke {t['Rail.stroke']:g}pt")
    row("t-opal", f"{r},{g},{b}", "JewelFace.opal")
    # inside a card
    row("t-c-gap", cqw(t["Card.vstackSpacing"]), f"Card.vstackSpacing {t['Card.vstackSpacing']:g}pt")
    # the feed's stack spacing ALSO in card-widths: the diagram stacks real cards
    # by their own width, so it needs the gap in that unit rather than the frame's
    row("t-c-feedgap", cqw(t["Feed.stackSpacing"]), f"Feed.stackSpacing {t['Feed.stackSpacing']:g}pt, in card widths")
    row("t-c-headgap", cqw(t["Card.headerGap"]), f"Card.headerGap {t['Card.headerGap']:g}pt")
    row("t-c-line", cqw(t["Card.lineInset"]), f"Card.lineInset {t['Card.lineInset']:g}pt")
    row("t-c-prov", cqw(t["Card.provenanceDot"]), f"Card.provenanceDot {t['Card.provenanceDot']:g}pt")
    row("t-c-author", cqw(t["Card.authorSize"]), f"Card.authorSize {t['Card.authorSize']:g}pt")
    row("t-c-loc", cqw(t["Card.locationSize"]), f"Card.locationSize {t['Card.locationSize']:g}pt")
    row("t-c-title", cqw(t["Card.titleSize"]), f"Card.titleSize {t['Card.titleSize']:g}pt")
    row("t-c-titlein", cqw(t["Card.titleInset"]), f"Card.titleInset {t['Card.titleInset']:g}pt")
    row("t-c-foot", cqw(t["Card.footerSize"]), f"Card.footerSize {t['Card.footerSize']:g}pt")
    row("t-c-hair", cqw(t["Card.hairline"]), f"Card.hairline {t['Card.hairline']:g}pt")
    # motion — a spring is a contract too
    row("t-perch-spring", f"{t['Motion.perchResponse']:g}", "Motion.perchResponse (s)")
    row("t-perch-damp", f"{t['Motion.perchDamping']:g}", "Motion.perchDamping")
    L.append("  }")
    L.append(END)
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("page", type=pathlib.Path, help="the diagram page holding the @tokens block")
    args = ap.parse_args()
    PAGE = args.page

    tokens = parse_swift(SWIFT.read_text())
    block = render(tokens)
    page = PAGE.read_text()

    if BEGIN not in page or END not in page:
        print(f"error: {PAGE.name} has no @tokens block — add the markers first", file=sys.stderr)
        return 2
    cur = page[page.index(BEGIN):page.index(END) + len(END)]

    if args.check:
        if cur != block:
            print("design tokens are STALE: the diagram no longer matches DesignTokens.swift.\n"
                  "run pacific/scripts/design-tokens.py", file=sys.stderr)
            return 1
        print(f"design tokens current ({len(tokens)} tokens)")
        return 0

    if cur == block:
        print(f"design tokens already current ({len(tokens)} tokens)")
        return 0
    PAGE.write_text(page.replace(cur, block))
    print(f"design tokens written ({len(tokens)} tokens) -> {PAGE.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
